def _epic_family(*, second_closed=True, reason=None, grandparent=None):
    """Epic 1 com as filhas 2 e 3; a 3 acabou de fechar."""
    return {
        1: _issue(1, parent=grandparent, sub_issues=(2, 3)),
        2: _issue(2, parent=1, closed=second_closed, reason=reason, title="A"),
        3: _issue(3, parent=1, closed=True, reason=reason, title="B"),
    }


class GithubIssuesTest(unittest.TestCase):
    def capture(self):
        self._stdout = io.StringIO()
        context = redirect_stdout(self._stdout)
        context.__enter__()
        self.addCleanup(context.__exit__, None, None, None)

    def output(self):
        value = self._stdout.getvalue()
        self._stdout.seek(0)
        self._stdout.truncate()
        return value

    def test_reference_keywords_and_trailers(self):
        assert referenced_issues("feat: x\n\nRefs #12") == [12]
        assert referenced_issues("fix: y\n\nRefs: #3\nCloses #4") == [3, 4]
        assert referenced_issues("docs: z\n\nPart of alaorneto/skeleton#7", REPO) == [7]
        assert referenced_issues("feat: squash subject (#21)") == [21]

    def test_bare_hash_and_other_repositories_do_not_count(self):
        assert referenced_issues("feat: support #12 colors") == []
        assert referenced_issues("Refs other/repo#5", REPO) == []

    def test_comments_and_scissors_are_ignored(self):
        raw = "feat: x\n# Refs #9\n# ------------------------ >8 ------------------------\nRefs #10\n"
        assert referenced_issues(clean_message(raw)) == []

    def test_branch_number_and_autogenerated_messages(self):
        assert issue_from_branch("feat/42-platform-users") == 42
        assert issue_from_branch("42-hotfix") == 42
        assert issue_from_branch("ci/lint-and-pipeline") is None
        assert issue_from_branch("deps/bump-1-2") is None
        assert is_autogenerated("Merge branch 'main' into feat/1-x")
        assert is_autogenerated('Revert "feat: x"')
        assert not is_autogenerated("feat: merge forms")

    def test_pr_requires_existing_typed_issue(self):
        fetch = _issues(n1=_labels("feature", "security"), n2=_labels(), n3={"pull_request": {}}, n4=_labels("epic"))
        assert validate_pr("Closes #1", REPO, fetch) == []
        assert validate_pr("Closes #1\nParte de #4\nRefs #4", REPO, fetch) == []
        assert validate_pr("Nada aqui", REPO, fetch)
        assert "label de tipo" in validate_pr("Closes #2", REPO, fetch)[0]
        assert "pull request" in validate_pr("Fixes #3", REPO, fetch)[0]
        assert "não existe" in validate_pr("Resolves #99", REPO, fetch)[0]
        assert "epics" in validate_pr("Refs #4", REPO, fetch)[0]

    def test_pr_rejects_two_type_labels(self):
        fetch = _issues(n5=_labels("bug", "feature"))
        assert "exatamente um" in validate_pr("Closes #5", REPO, fetch)[0]

    def test_parse_epic_items_reads_only_the_items_section(self):
        plan = parse_epic_items(EPIC_BODY, REPO)
        assert plan.items == [
            EpicItem(96),
            EpicItem(97),
            EpicItem(98, (97,)),
            EpicItem(101, (98, 100)),
            EpicItem(102),
        ]
        assert plan.candidates == 1
        assert len(plan.problems) == 3
        assert any("outro repositório" in p and "other/repo#5" in p for p in plan.problems)
        assert any("other/repo#9" in p for p in plan.problems)
        assert any("#96 aparece mais de uma vez" in p for p in plan.problems)

    def test_parse_epic_items_without_items_section(self):
        plan = parse_epic_items("## Contexto\n- [ ] #1 x\n", REPO)
        assert plan.items == [] and plan.problems == [] and plan.candidates == 0

    def test_plan_epic_creates_missing_links_only(self):
        plan = _plan(EpicItem(96), EpicItem(97), EpicItem(98, (97,)))
        links = {
            112: IssueLinks(112, sub_issues=(97,)),
            96: IssueLinks(96),
            97: IssueLinks(97, parent=112),
            98: IssueLinks(98),
        }
        operations, problems = plan_epic(112, plan, links)
        assert operations == [
            Operation("sub-issue", 112, 96),
            Operation("sub-issue", 112, 98),
            Operation("blocked-by", 98, 97),
        ]
        assert problems == []

    def test_plan_epic_is_idempotent_once_linked(self):
        plan = _plan(EpicItem(96), EpicItem(98, (97,)), EpicItem(97))
        links = {
            112: IssueLinks(112, sub_issues=(96, 97, 98)),
            96: IssueLinks(96, parent=112),
            97: IssueLinks(97, parent=112),
            98: IssueLinks(98, parent=112, blocked_by=(97,)),
        }
        assert plan_epic(112, plan, links) == ([], [])

    def test_plan_epic_never_replaces_an_existing_parent(self):
        plan = _plan(EpicItem(96), EpicItem(97))
        links = {112: IssueLinks(112), 96: IssueLinks(96, parent=95), 97: IssueLinks(97, parent="other/repo#3")}
        operations, problems = plan_epic(112, plan, links)
        assert operations == []
        assert any("#96 já é sub-issue de #95" in p for p in problems)
        assert any("#97 já é sub-issue de other/repo#3" in p for p in problems)

    def test_plan_epic_reports_missing_issues_and_unlisted_sub_issues(self):
        plan = _plan(EpicItem(96, (300,)), EpicItem(301), EpicItem(112))
        links = {112: IssueLinks(112, sub_issues=(96, 150)), 96: IssueLinks(96, parent=112), 300: None, 301: None}
        operations, problems = plan_epic(112, plan, links)
        assert operations == []
        assert any("depende de #300" in p for p in problems)
        assert any("#301 não existe" in p for p in problems)
        assert any("lista a si mesmo" in p for p in problems)
        assert any("#150 é sub-issue de #112 mas não está" in p for p in problems)
        assert plan_epic(999, plan, {999: None})[1][-1].startswith("#999 não existe")

    def test_plan_epic_skips_issues_shared_by_two_epics(self):
        plans = {1: _plan(EpicItem(10), EpicItem(11)), 2: _plan(EpicItem(10))}
        assert shared_items(plans) == {10: [1, 2]}
        links = {1: IssueLinks(1), 10: IssueLinks(10), 11: IssueLinks(11)}
        operations, _ = plan_epic(1, plans[1], links, skip=shared_items(plans))
        assert operations == [Operation("sub-issue", 1, 11)]

