class FakeGh:
    """Simula o `gh`: responde leituras a partir de ``issues`` e registra as escritas."""

    def __init__(self, epics, issues, fail=(), clobber_once=False, labels=None, close_fails=False):
        self.epics = epics  # {numero: corpo}
        self.issues = issues  # {numero: nó GraphQL}
        self.fail = set(fail)
        self.clobber_once = clobber_once  # simula outra execução gravando um corpo antigo
        self.labels = labels or {}  # {numero: [labels]} devolvidos por `gh issue view`
        self.close_fails = close_fails
        self.writes = []
        self.bodies = []
        self.closes = []

    def __call__(self, args):
        args = list(args)
        if args[:2] == ["issue", "list"]:
            data = [{"number": n, "body": b, "labels": [{"name": "epic"}]} for n, b in self.epics.items()]
            return subprocess.CompletedProcess(args, 0, json.dumps(data), "")
        if args[:2] == ["issue", "view"]:
            n = int(args[2])
            node = self.issues.get(n) or {}
            data = {
                "number": n,
                "body": self.epics.get(n, ""),
                "labels": [{"name": name} for name in self.labels.get(n, [])],
                "state": node.get("state", "OPEN"),
            }
            return subprocess.CompletedProcess(args, 0, json.dumps(data), "")
        if args[:2] == ["issue", "close"]:
            n = int(args[2])
            self.closes.append((n, args[args.index("--reason") + 1], args[args.index("--comment") + 1]))
            if self.close_fails:
                return subprocess.CompletedProcess(args, 1, "", "sem permissão")
            self.issues[n] = {**self.issues[n], "state": "CLOSED"}
            return subprocess.CompletedProcess(args, 0, "", "")
        if args[:2] == ["api", "graphql"]:
            numbers = [int(n) for n in re.findall(r"\bi(\d+):", args[-1])]
            data = {"repository": {f"i{n}": self.issues.get(n) for n in numbers}}
            return subprocess.CompletedProcess(args, 1, json.dumps({"data": data, "errors": []}), "")
        if args[:2] == ["issue", "edit"] and args[5] == "--body-file":
            number, old = int(args[2]), self.epics[int(args[2])]
            with open(args[6], encoding="utf-8", newline="") as file:
                self.epics[number] = file.read()
            self.bodies.append((number, self.epics[number]))
            if self.clobber_once:
                self.clobber_once = False
                self.epics[number] = old
            return subprocess.CompletedProcess(args, 0, "", "")
        if args[:2] == ["issue", "edit"]:
            self.writes.append((int(args[2]), args[5], int(args[6])))
            failed = (int(args[2]), int(args[6])) in self.fail
            return subprocess.CompletedProcess(args, 1 if failed else 0, "", "boom" if failed else "")
        raise AssertionError(args)


def _issue(number, parent=None, blocked_by=(), closed=False, sub_issues=(), reason=None, title=None):
    def ref(value):
        repo, _, n = str(value).rpartition("#")
        return {"number": int(n), "repository": {"nameWithOwner": repo or REPO}}

    return {
        "__typename": "Issue",
        "number": number,
        "title": title or f"Issue {number}",
        "state": "CLOSED" if closed else "OPEN",
        "stateReason": (reason or "COMPLETED") if closed else None,
        "parent": {"number": parent, "repository": {"nameWithOwner": REPO}} if parent else None,
        "subIssues": {"nodes": [ref(child) for child in sub_issues]},
        "blockedBy": {"nodes": [{"number": b, "repository": {"nameWithOwner": REPO}} for b in blocked_by]},
    }


