def test_epic_is_not_closed_unless_every_sub_issue_is_closed(capsys):
    cases = [
        ("open_child", "continua aberto: #2"),
        ("no_label", "não tem o label epic"),
        ("already_closed", "já está fechado"),
        ("no_sub_issues", "não tem sub-issues nativas"),
        ("foreign", "outro repositório"),
        ("no_parent", "não é sub-issue"),
    ]
    for change, message in cases:
        issues = _epic_family(second_closed=change != "open_child")
        labels = {1: [] if change == "no_label" else ["epic"]}
        if change == "already_closed":
            issues[1] = {**issues[1], "state": "CLOSED"}
        if change == "no_sub_issues":
            issues[1] = _issue(1)
        if change == "foreign":
            issues[1] = _issue(1, sub_issues=(2, 3, "other/repo#5"))
        if change == "no_parent":
            issues[3] = _issue(3, closed=True)
        gh = FakeGh({1: SMALL_EPIC}, issues, labels=labels)
        assert close_completed_parents(3, REPO, dry_run=False, gh=gh) == 0, change
        assert gh.closes == [] and gh.bodies == [], change
        assert message in capsys.readouterr().out, change


