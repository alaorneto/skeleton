"""Vínculo entre trabalho versionado e issues do GitHub.

Subcomandos (``github_issues.py <subcomando>``), todos só com a biblioteca padrão:

- ``commit-msg ARQUIVO``: hook ``commit-msg``. Aceita mensagens que referenciam uma issue; senão
  acrescenta ``Refs: #N`` a partir da branch ``<tipo>/<N>-<slug>``; senão recusa o commit.
- ``check-pr [--pr N]``: verificação do PR (issue vinculada e classificada, seções do modelo,
  classificação de versão, título). No CI lê ``PR_NUMBER`` e ``GITHUB_REPOSITORY``.
- ``pr-merged [--pr N]``: depois do merge, registra as evidências em cada issue do PR e classifica
  como ``no-release`` o PR que ninguém classificou.
- ``start N [--dry-run]``: cria a branch ``<prefixo>/<N>-<slug>`` a partir da issue.
- ``sync-labels``: cria ou atualiza os labels do fluxo.
- ``sync-epic``, ``sync-checklist``, ``close-epic``: veja ``epics.py``.
"""

from __future__ import annotations

import os
import re
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from . import epics
from .config import Config, ConfigError, load
from .gh import Git, GitHub, current_repository, is_trusted_author, label_names, run_gh, utf8_streams
from .text import (
    checkboxes,
    clean_message,
    is_autogenerated,
    issue_from_branch,
    marked_value,
    meaningful,
    parse_conventional,
    referenced_issues,
    section,
    sections,
    slugify,
)

IssueFetcher = Callable[[int], "dict[str, Any] | None"]
EVIDENCE_MARK = "<!-- dev-workflow:evidence pr={number} -->"
UNCLASSIFIED_MARK = "<!-- dev-workflow:unclassified -->"


# --- commit-msg --------------------------------------------------------------------------------


def commit_msg(path: Path, cfg: Config, git: Git | None = None) -> int:
    git = git or Git()
    message = clean_message(path.read_text(encoding="utf-8", errors="replace"))
    first_line = message.splitlines()[0] if message else ""
    if not message or is_autogenerated(message) or cfg.release_subject_pattern().match(first_line):
        return 0
    if referenced_issues(message):
        return 0
    branch = git("symbolic-ref", "--short", "HEAD", check=False)  # vazio com HEAD destacado
    issue = issue_from_branch(branch)
    if issue is not None:
        git(
            "interpret-trailers",
            "--in-place",
            "--if-exists",
            "addIfDifferent",
            "--trailer",
            f"Refs: #{issue}",
            str(path),
        )
        print(f"commit-msg: 'Refs: #{issue}' acrescentado a partir da branch {branch}.")
        return 0
    print(
        "commit-msg: o commit precisa referenciar uma issue do GitHub.\n"
        "  Acrescente um trailer 'Refs #N' (ou trabalhe numa branch <tipo>/<N>-<slug>).\n"
        "  Sem issue? Crie uma antes: veja o skill dev-workflow.",
        file=sys.stderr,
    )
    return 1


# --- check-pr ----------------------------------------------------------------------------------


@dataclass
class Findings:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def add(self, severity: str, message: str) -> None:
        if severity == "error":
            self.errors.append(message)
        elif severity == "warning":
            self.warnings.append(message)


def issue_type(issue: dict[str, Any] | None, cfg: Config) -> str | None:
    """O label de tipo da issue, quando há exatamente um."""
    types = sorted(label_names(issue) & set(cfg.type_labels))
    return types[0] if len(types) == 1 else None


def validate_links(body: str, repository: str, fetch: IssueFetcher, cfg: Config) -> list[str]:
    """Erros de vínculo: o PR cita ao menos uma issue existente com exatamente um label de tipo."""
    numbers = referenced_issues(body, repository)
    if not numbers:
        return ["O corpo do PR não referencia issue: use `Closes #N` (entrega completa) ou `Refs #N` (parcial)."]
    errors: list[str] = []
    typed = 0
    for number in numbers:
        issue = fetch(number)
        if issue is None:
            errors.append(f"#{number} não existe em {repository}.")
            continue
        if "pull_request" in issue:
            errors.append(f"#{number} é um pull request, não uma issue.")
            continue
        labels = label_names(issue)
        if cfg.label("epic") in labels:
            continue
        types = sorted(labels & set(cfg.type_labels))
        if len(types) != 1:
            found = ", ".join(types) or "nenhum"
            errors.append(
                f"#{number} precisa de exatamente um label de tipo ({', '.join(cfg.type_labels)}); encontrado: {found}."
            )
            continue
        typed += 1
    if typed == 0 and not errors:
        errors.append("O PR referencia apenas epics; cite a issue filha entregue (`Closes #N`).")
    return errors


def is_exempt(pr: dict[str, Any], cfg: Config) -> str | None:
    """Motivo da isenção das verificações, ou ``None``."""
    author = str((pr.get("user") or {}).get("login", ""))
    if author in cfg.pr["exempt_authors"]:
        return f"PR de {author}: isento do fluxo de issues."
    if str((pr.get("head") or {}).get("ref", "")) == cfg.release["pr_branch"]:
        return "PR de release gerado pela automação: isento."
    return None


def classification(labels: set[str], cfg: Config) -> tuple[str | None, list[str]]:
    """``("release" | "no-release" | None, níveis de sobreposição)`` lidos dos labels do PR."""
    chosen = [key for key in ("release", "no_release") if cfg.label(key) in labels]
    prefix = cfg.label("override_prefix")
    overrides = sorted(label[len(prefix) :] for label in labels if label.startswith(prefix))
    return (chosen[0] if len(chosen) == 1 else None), overrides


def override_reason(body: str, cfg: Config) -> str:
    """Texto depois de ``Motivo da sobreposição:`` na seção de versão do PR."""
    return marked_value(section(body, cfg.pr["version_section"]), str(cfg.pr["override_reason_marker"]))


def check_pull_request(pr: dict[str, Any], repository: str, fetch: IssueFetcher, cfg: Config) -> Findings:
    findings = Findings()
    exemption = is_exempt(pr, cfg)
    if exemption:
        findings.notes.append(exemption)
        return findings
    body = str(pr.get("body") or "")
    title = str(pr.get("title") or "")
    labels = label_names(pr)

    findings.errors.extend(validate_links(body, repository, fetch, cfg))

    present = sections(body)
    for name in cfg.pr["required_sections"]:
        text = present.get(name.casefold())
        if text is None:
            findings.add(cfg.severity("sections"), f"Falta a seção `## {name}` no corpo do PR (use o modelo de PR).")
        elif not meaningful(text):
            findings.add(
                cfg.severity("sections"),
                f"A seção `## {name}` está vazia: preencha ou escreva `Não se aplica — motivo`.",
            )

    if cfg.versioning_enabled:
        release, no_release = cfg.label("release"), cfg.label("no_release")
        chosen, overrides = classification(labels, cfg)
        if chosen is None:
            both = release in labels and no_release in labels
            findings.add(
                cfg.severity("classification"),
                (f"O PR tem os labels `{release}` e `{no_release}`; deixe só um. " if both else "")
                + f"Classifique o PR com exatamente um label: `{release}` (o merge publica uma versão com tudo que "
                f"está acumulado desde a última tag) ou `{no_release}` (fica acumulado para a próxima versão).",
            )
        if len(overrides) > 1:
            findings.errors.append(f"Mais de um label de sobreposição ({', '.join(overrides)}); deixe só um.")
        elif overrides:
            if overrides[0] not in ("major", "minor", "patch"):
                findings.errors.append(f"`{cfg.override_label(overrides[0])}` não é major, minor nem patch.")
            if chosen != "release":
                findings.errors.append(
                    f"`{cfg.override_label(overrides[0])}` só vale em PR marcado com `{release}`: a sobreposição "
                    "decide o número da versão que este PR publica."
                )
            if not override_reason(body, cfg):
                findings.errors.append(
                    f"Sobreposição de versão sem motivo: escreva `{cfg.pr['override_reason_marker']}: <motivo>` "
                    f"na seção `## {cfg.pr['version_section']}`."
                )

    conventional = parse_conventional(title)
    if not re.match(cfg.pr["title_pattern"], title):
        findings.add(
            cfg.severity("title"),
            f"O título `{title}` não segue Conventional Commits (`<tipo>(<escopo>): <assunto>`); ele vira o commit "
            "de um squash e entra no changelog.",
        )

    closing = referenced_issues(body, repository, closing_only=True)
    types_seen: set[str] = set()
    for number in referenced_issues(body, repository):
        issue = fetch(number)
        kind = issue_type(issue, cfg)
        if issue is None or "pull_request" in issue or kind is None:
            continue
        types_seen.add(kind)
        if number not in closing:
            continue
        issue_body = str(issue.get("body") or "")
        missing = [
            name for name in cfg.issue_sections(kind) if not meaningful(sections(issue_body).get(name.casefold()))
        ]
        if missing:
            findings.add(
                cfg.severity("issue_sections"),
                f"#{number} está sem as seções do modelo: {', '.join(missing)} (use `Não se aplica — motivo`).",
            )
        boxes = checkboxes(section(issue_body, cfg.issues["acceptance_section"]))
        pending = [label for done, label in boxes if not done]
        if pending:
            findings.add(
                cfg.severity("unchecked_criteria"),
                f"#{number} tem {len(pending)} de {len(boxes)} critérios de aceite sem marcar; marque os "
                "verificados ou registre a dispensa na issue antes do merge.",
            )
    if conventional and types_seen:
        accepted = {prefix for kind in types_seen for prefix in cfg.types[kind]["prefixes"]}
        if conventional.type not in accepted:
            findings.add(
                cfg.severity("type_mismatch"),
                f"O título usa `{conventional.type}`, mas as issues vinculadas são de tipo {', '.join(sorted(types_seen))} "
                f"(prefixos esperados: {', '.join(sorted(accepted))}). Confira a classificação.",
            )
    return findings


def _annotate(kind: str, message: str) -> None:
    single = message.replace("\r", " ").replace("\n", " ")
    if os.environ.get("GITHUB_ACTIONS"):
        print(f"::{kind} title=Verificação do PR::{single}")
    else:
        print(f"{'ERRO' if kind == 'error' else 'aviso'}: {single}")


def _pr_number(args: Sequence[str]) -> int | None:
    value = args[args.index("--pr") + 1] if "--pr" in args and args.index("--pr") + 1 < len(args) else ""
    value = value or os.environ.get("PR_NUMBER", "")
    return int(value.lstrip("#")) if value.lstrip("#").isdigit() else None


def check_pr_command(args: Sequence[str], cfg: Config) -> int:
    number = _pr_number(args)
    github = GitHub(current_repository(Git(cfg.root)))
    if number is None or not github.enabled:
        print(
            "uso: github_issues.py check-pr --pr N (ou PR_NUMBER), com GITHUB_REPOSITORY ou `gh` autenticado",
            file=sys.stderr,
        )
        return 2
    pr = github.pull(number)
    if pr is None:
        print(f"PR #{number} não encontrado em {github.repository}.", file=sys.stderr)
        return 1
    cache: dict[int, dict[str, Any] | None] = {}

    def fetch(issue: int) -> dict[str, Any] | None:
        if issue not in cache:
            cache[issue] = github.issue(issue)
        return cache[issue]

    findings = check_pull_request(pr, str(github.repository), fetch, cfg)
    for note in findings.notes:
        print(note)
    for warning in findings.warnings:
        _annotate("warning", warning)
    for error in findings.errors:
        _annotate("error", error)
    if not findings.errors:
        print(f"PR #{number} verificado: {len(findings.warnings)} aviso(s).")
    return 1 if findings.errors else 0


# --- pr-merged ---------------------------------------------------------------------------------


def evidence_comment(
    pr: dict[str, Any], commits: Sequence[dict[str, Any]], issue: dict[str, Any], cfg: Config, *, closing: bool
) -> str:
    number = int(pr["number"])
    body = str(pr.get("body") or "")
    merged_by = str((pr.get("merged_by") or {}).get("login", "")) or "merge"
    lines = [EVIDENCE_MARK.format(number=number)]
    if closing:
        lines.append(
            f"**Entregue pelo PR #{number}**, mesclado por @{merged_by}."
            if merged_by != "merge"
            else f"**Entregue pelo PR #{number}.**"
        )
    else:
        lines.append(f"**Entrega parcial pelo PR #{number}** (o PR cita esta issue com `Refs`; ela continua aberta).")
    lines += ["", "**Commits**"]
    for commit in commits:
        subject = str((commit.get("commit") or {}).get("message", "")).splitlines()[0:1]
        lines.append(f"- {str(commit.get('sha', ''))[:7]} {subject[0] if subject else ''}".rstrip())
    if not commits:
        lines.append("- (a lista de commits não pôde ser lida; veja o PR)")
    if closing:
        for label, key in (("Testes executados", "tests_section"), ("Documentação", "docs_section")):
            text = meaningful(section(body, cfg.pr[key]))
            lines += ["", f"**{label}** (declarado no PR)", text or "- Não informado no PR."]
        boxes = checkboxes(section(str(issue.get("body") or ""), cfg.issues["acceptance_section"]))
        pending = [label for done, label in boxes if not done]
        lines.append("")
        if not boxes:
            lines.append("**Critérios de aceite:** a issue não tem lista de critérios.")
        elif pending:
            lines.append(f"**Critérios de aceite:** {len(pending)} de {len(boxes)} sem marcar no momento do merge:")
            lines += [f"- [ ] {label}" for label in pending]
            lines.append("Marque-os se foram verificados, ou reabra a issue e registre o que falta.")
        else:
            lines.append(f"**Critérios de aceite:** os {len(boxes)} marcados.")
        if cfg.versioning_enabled:
            chosen, _ = classification(label_names(pr), cfg)
            lines.append("")
            if chosen == "release":
                lines.append(
                    "**Versão:** o PR está marcado para versionar; a automação de release comenta aqui quando a versão sair."
                )
            else:
                lines.append(
                    "**Versão:** o PR não gera versão; esta entrega fica acumulada e entra na próxima versão publicada."
                )
    return "\n".join(lines) + "\n"


def pr_merged(number: int, github: GitHub, cfg: Config) -> int:
    pr = github.pull(number)
    if pr is None:
        print(f"PR #{number} não encontrado.", file=sys.stderr)
        return 1
    if not pr.get("merged"):
        print(f"PR #{number} não foi mesclado; nada a registrar.")
        return 0
    trusted = cfg.versioning["trusted_bots"]
    labels = label_names(pr)
    exempt = is_exempt(pr, cfg)
    if cfg.versioning_enabled and str((pr.get("head") or {}).get("ref", "")) != cfg.release["pr_branch"]:
        chosen, _ = classification(labels, cfg)
        if chosen is None and cfg.label("release") not in labels:
            github.add_labels(number, [cfg.label("no_release")])
            if not exempt and not any(UNCLASSIFIED_MARK in str(c.get("body", "")) for c in github.comments(number)):
                github.add_comment(
                    number,
                    f"{UNCLASSIFIED_MARK}\nEste PR foi mesclado sem classificação de versão. Ficou marcado como "
                    f"`{cfg.label('no_release')}`: as mudanças estão acumuladas e entram na próxima versão publicada.\n",
                )
            print(f"PR #{number} sem classificação: marcado como {cfg.label('no_release')}.")
    if exempt:
        print(exempt)
        return 0
    body = str(pr.get("body") or "")
    repository = str(github.repository)
    closing = set(referenced_issues(body, repository, closing_only=True))
    commits = github.pull_commits(number)
    mark = EVIDENCE_MARK.format(number=number)
    for issue_number in referenced_issues(body, repository):
        issue = github.issue(issue_number)
        if issue is None or "pull_request" in issue or cfg.label("epic") in label_names(issue):
            continue
        existing = github.comments(issue_number)
        if any(mark in str(c.get("body", "")) and is_trusted_author(c, trusted) for c in existing):
            print(f"#{issue_number}: evidências do PR #{number} já registradas.")
            continue
        github.add_comment(issue_number, evidence_comment(pr, commits, issue, cfg, closing=issue_number in closing))
        print(f"#{issue_number}: evidências do PR #{number} registradas.")
    return 0


# --- start -------------------------------------------------------------------------------------


def branch_name(issue: dict[str, Any], cfg: Config) -> str:
    kind = issue_type(issue, cfg)
    if kind is None:
        raise ValueError(
            f"#{issue.get('number')} precisa de exatamente um label de tipo ({', '.join(cfg.type_labels)}) "
            "antes de virar branch."
        )
    return f"{cfg.types[kind]['prefixes'][0]}/{issue['number']}-{slugify(str(issue.get('title', '')))}"


def start(number: int, github: GitHub, cfg: Config, git: Git, *, dry_run: bool) -> int:
    issue = github.issue(number)
    if issue is None or "pull_request" in issue:
        print(f"#{number} não é uma issue de {github.repository}.", file=sys.stderr)
        return 1
    try:
        name = branch_name(issue, cfg)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    if dry_run:
        print(name)
        return 0
    if git("status", "--porcelain"):
        print(
            "A árvore de trabalho tem mudanças: commit, descarte ou use outro worktree antes de trocar de branch.",
            file=sys.stderr,
        )
        return 1
    base = f"origin/{cfg.default_branch}"
    git("fetch", "origin", cfg.default_branch)
    git("switch", "-c", name, base)
    print(f"Branch {name} criada a partir de {base}.")
    return 0


# --- sync-labels -------------------------------------------------------------------------------


def sync_labels(cfg: Config) -> int:
    failed = False
    for name, (color, description) in cfg.all_labels().items():
        completed = run_gh(["label", "create", name, "--color", color, "--description", description, "--force"])
        failed |= completed.returncode != 0
        print(f"label {name} {'ok' if completed.returncode == 0 else 'ERRO: ' + completed.stderr.strip()}")
    return 1 if failed else 0


# --- linha de comando --------------------------------------------------------------------------

SYNC_EPIC_USAGE = "sync-epic (N [N...] | --all) [--dry-run]"
SYNC_CHECKLIST_USAGE = "sync-checklist (N [N...] | --all | --parent-of N) [--dry-run]"
CLOSE_EPIC_USAGE = "close-epic --parent-of N [--dry-run]"
USAGE = (
    f"commit-msg ARQUIVO | check-pr [--pr N] | pr-merged [--pr N] | start N [--dry-run] | sync-labels | "
    f"{SYNC_EPIC_USAGE} | {SYNC_CHECKLIST_USAGE} | {CLOSE_EPIC_USAGE}"
)


def _repository() -> str:
    repository = current_repository(Git())
    if not repository:
        raise RuntimeError("não consegui identificar o repositório (GITHUB_REPOSITORY, remoto origin ou `gh`).")
    return repository


def _close_epic_command(args: Sequence[str]) -> int:
    rest = [arg for arg in args if arg != "--dry-run"]
    if len(rest) != 2 or rest[0] != "--parent-of" or not rest[1].lstrip("#").isdigit():
        print(f"uso: github_issues.py {CLOSE_EPIC_USAGE}", file=sys.stderr)
        return 2
    try:
        return epics.close_completed_parents(int(rest[1].lstrip("#")), _repository(), dry_run="--dry-run" in args)
    except RuntimeError as exc:
        print(f"close-epic: {exc}", file=sys.stderr)
        return 1


def _sync_command(name: str, args: Sequence[str]) -> int:
    usage = SYNC_EPIC_USAGE if name == "sync-epic" else SYNC_CHECKLIST_USAGE
    dry_run = "--dry-run" in args
    everything = "--all" in args
    options = {"--dry-run", "--all"} | ({"--parent-of"} if name == "sync-checklist" else set())
    parent_of = "--parent-of" in args
    numbers = [arg.lstrip("#") for arg in args if arg not in options]
    valid = all(number.isdigit() for number in numbers) and (
        len(numbers) == 1 and not everything if parent_of else everything != bool(numbers)
    )
    if not valid:
        print(f"uso: github_issues.py {usage}", file=sys.stderr)
        return 2
    selection = None if everything else [int(n) for n in numbers]
    try:
        repository = _repository()
        if name == "sync-epic":
            return epics.sync_epic(selection, repository, dry_run=dry_run)
        if parent_of:
            return epics.sync_parent_checklist(int(numbers[0]), repository, dry_run=dry_run)
        return epics.sync_checklist(selection, repository, dry_run=dry_run)
    except RuntimeError as exc:
        print(f"{name}: {exc}", file=sys.stderr)
        return 1


def main(argv: Sequence[str] | None = None) -> int:
    utf8_streams()
    args = list(sys.argv[1:] if argv is None else argv)
    try:
        cfg = load()
    except ConfigError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    epics.configure(
        items_section=cfg.issues["items_section"],
        depends_marker=cfg.issues["depends_marker"],
        epic_label=cfg.label("epic"),
    )
    if args[:1] == ["commit-msg"] and len(args) == 2:
        return commit_msg(Path(args[1]), cfg)
    if args[:1] == ["check-pr"]:
        return check_pr_command(args[1:], cfg)
    if args[:1] == ["pr-merged"]:
        number = _pr_number(args[1:])
        if number is None:
            print("uso: github_issues.py pr-merged --pr N (ou PR_NUMBER)", file=sys.stderr)
            return 2
        return pr_merged(number, GitHub(_repository()), cfg)
    if args[:1] == ["start"] and len(args) >= 2 and args[1].lstrip("#").isdigit():
        git = Git(cfg.root)
        return start(int(args[1].lstrip("#")), GitHub(_repository()), cfg, git, dry_run="--dry-run" in args)
    if args == ["sync-labels"]:
        return sync_labels(cfg)
    if args[:1] in (["sync-epic"], ["sync-checklist"]):
        return _sync_command(args[0], args[1:])
    if args[:1] == ["close-epic"]:
        return _close_epic_command(args[1:])
    print(f"uso: github_issues.py {USAGE}", file=sys.stderr)
    return 2
