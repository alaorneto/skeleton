"""Leitura de mensagens de commit e de corpos Markdown de issues e PRs."""

from __future__ import annotations

import functools
import re
import unicodedata
from collections.abc import Iterable, Iterator
from dataclasses import dataclass

from . import i18n

_ISSUE = r"(?:(?P<repo>[\w.-]+/[\w.-]+))?#(?P<number>\d+)"
_CLOSING = r"close[sd]?|fix(?:e[sd])?|resolve[sd]?"
ISSUE_REFERENCE = re.compile(rf"\b(?P<keyword>{_CLOSING}|refs?|part of)\b\s*:?\s+{_ISSUE}", re.IGNORECASE)
# Continuação de uma lista depois da primeira referência: ``Refs #5, #6 and #7``.
LIST_TAIL = re.compile(rf"\s*(?:,\s*(?:and\s+)?|\s+and\s+){_ISSUE}", re.IGNORECASE)
CLOSING_KEYWORD = re.compile(rf"^(?:{_CLOSING})$", re.IGNORECASE)
ANY_ISSUE = re.compile(_ISSUE)
ITEM_ISSUE = re.compile(rf"^{_ISSUE}\b")
SQUASH_SUFFIX = re.compile(r"\(#(?P<number>\d+)\)\s*$")
MERGE_PR = re.compile(r"^Merge pull request #(?P<number>\d+) from (?:(?P<owner>[^/\s]+)/(?P<branch>\S+))?")
BRANCH_ISSUE = re.compile(r"^(?P<prefix>[\w.-]+)/(?P<number>\d+)-")
AUTOGENERATED = re.compile(r'^(?:Merge |Revert "|fixup! |squash! |amend! )')
REVERTS = re.compile(r"This reverts commit ([0-9a-f]{7,40})")
SCISSORS = re.compile(r"^# -+ >8 -+$", re.MULTILINE)
CONVENTIONAL = re.compile(r"^(?P<type>[a-z]+)(?:\((?P<scope>[^)]*)\))?(?P<bang>!)?: (?P<description>.+)$")
BREAKING_FOOTER = re.compile(r"^BREAKING[ -]CHANGE:\s*(?P<text>.+)$", re.MULTILINE)
HEADING = re.compile(r"^(?P<level>#{1,6})\s+(?P<title>.+?)\s*#*\s*$")
HTML_COMMENT = re.compile(r"<!--.*?(?:-->|\Z)", re.DOTALL)
INLINE_CODE = re.compile(r"(?P<ticks>`+)(?!`).*?(?<!`)(?P=ticks)(?!`)")
FENCE = re.compile(r"^\s{0,3}(?P<fence>`{3,}|~{3,})")
CHECKBOX = re.compile(r"^\s*[-*]\s+\[(?P<mark>[ xX])\]\s+(?P<label>.*)$")
_PLACEHOLDER_LINE = re.compile(r"^[\s>*_`-]*(?:\[[ xX]?\])?[\s>*_`-]*$")
NO_RESPONSE = "_No response_"  # o que os formulários de issue do GitHub gravam em campos vazios


def same_repo(repo: str | None, repository: str | None) -> bool:
    return repo is None or repository is None or repo.lower() == repository.lower()


def clean_message(raw: str, comment_char: str = "#") -> str:
    """Remove o que o git descarta: tudo após a tesoura e as linhas de comentário."""
    match = SCISSORS.search(raw)
    if match:
        raw = raw[: match.start()]
    return "\n".join(line for line in raw.splitlines() if not line.startswith(comment_char)).strip()


def visible_text(text: str) -> str:
    """O texto que o GitHub mostra e vincula: sem comentários HTML, blocos de código e código em linha.

    Cada trecho removido vira espaço (ou quebra de linha, num bloco), para duas palavras vizinhas não se
    juntarem numa referência que não existe.
    """
    without_comments = HTML_COMMENT.sub(lambda match: "\n" * match.group(0).count("\n") or " ", text or "")
    lines: list[str] = []
    fence: str | None = None
    for line in without_comments.splitlines():
        opened = FENCE.match(line)
        if fence is None and opened:
            fence = opened.group("fence")
            lines.append("")
            continue
        if fence is not None:
            if line.strip().startswith(fence[0] * len(fence)) and not line.strip().strip(fence[0]):
                fence = None
            lines.append("")
            continue
        lines.append(INLINE_CODE.sub(" ", line))
    return "\n".join(lines)


def _references(text: str, repository: str | None) -> Iterator[tuple[str, int, bool]]:
    """``(palavra-chave, número, primeira_da_lista)`` de cada referência visível do repositório."""
    visible = visible_text(text)
    for match in ISSUE_REFERENCE.finditer(visible):
        keyword = match.group("keyword")
        refs = [(match.group("repo"), match.group("number"), True)]
        end = match.end()
        while tail := LIST_TAIL.match(visible, end):
            refs.append((tail.group("repo"), tail.group("number"), False))
            end = tail.end()
        for repo, number, first in refs:
            if same_repo(repo, repository):
                yield keyword, int(number), first


def referenced_issues(
    text: str, repository: str | None = None, *, closing_only: bool = False, squash_suffix: bool = True
) -> list[int]:
    """Números das issues citadas com palavra-chave; ignora outros repositórios.

    Só conta o que o GitHub mostra: referência em comentário HTML ou em bloco de código não vale. Uma
    lista (``Refs #5, #6``) vincula todas, mas o GitHub só fecha a primeira de ``Closes #5, #6``.
    O sufixo ``(#N)`` do título de um squash conta como referência, mas nunca como fechamento.
    """
    numbers: list[int] = []
    for keyword, number, first in _references(text, repository):
        if closing_only and not (first and CLOSING_KEYWORD.match(keyword)):
            continue
        numbers.append(number)
    if squash_suffix and not closing_only:
        first_line = text.strip().splitlines()[0] if text.strip() else ""
        suffix = SQUASH_SUFFIX.search(first_line)
        if suffix:
            numbers.append(int(suffix.group("number")))
    return list(dict.fromkeys(numbers))


def unclosed_list_items(text: str, repository: str | None = None) -> list[int]:
    """Issues de uma lista de fechamento que o GitHub não fecha: o ``#6`` de ``Closes #5, #6``."""
    closing = set(referenced_issues(text, repository, closing_only=True))
    found = (
        number
        for keyword, number, first in _references(text, repository)
        if not first and CLOSING_KEYWORD.match(keyword) and number not in closing
    )
    return list(dict.fromkeys(found))


def is_autogenerated(message: str) -> bool:
    return bool(AUTOGENERATED.match(message))


def issue_from_branch(branch: str, prefixes: Iterable[str] | None = None) -> int | None:
    """O número de uma branch ``<prefixo>/<N>-<slug>``; com ``prefixes``, só desses prefixos.

    ``feature/2024-q1-plan`` não é a issue 2024: ``feature`` não é prefixo de commit.
    """
    match = BRANCH_ISSUE.match(branch)
    if not match or (prefixes is not None and match.group("prefix") not in set(prefixes)):
        return None
    return int(match.group("number"))


@dataclass(frozen=True)
class Conventional:
    type: str
    scope: str | None
    breaking: bool
    description: str


def parse_conventional(subject: str) -> Conventional | None:
    match = CONVENTIONAL.match(subject.strip())
    if not match:
        return None
    return Conventional(match["type"], match["scope"], bool(match["bang"]), match["description"])


def breaking_notes(text: str) -> list[str]:
    """Textos dos rodapés ``BREAKING CHANGE:`` de uma mensagem de commit ou corpo de PR."""
    return [match.group("text").strip() for match in BREAKING_FOOTER.finditer(HTML_COMMENT.sub("", text))]


def normalize_title(title: str) -> str:
    return re.sub(r"\s+", " ", title).strip().strip(":").casefold()


def _comment_offsets(body: str) -> list[tuple[int, int]]:
    return [match.span() for match in HTML_COMMENT.finditer(body)]


def sections(body: str) -> dict[str, str]:
    """``{título normalizado: texto}`` para cada título de seção.

    Os formulários de issue do GitHub gravam ``###``; os modelos de PR usam ``##``. Uma seção vai até o
    próximo título do mesmo nível ou de nível acima, então um ``### Detalhes`` dentro de ``## Resumo``
    continua fazendo parte do resumo (e também pode ser lido sozinho). Títulos em bloco de código ou em
    comentário HTML não contam. Vale a primeira seção de cada título.
    """
    body = body or ""
    comments = _comment_offsets(body)
    result: dict[str, str] = {}
    open_sections: list[tuple[int, str, list[str], bool]] = []
    fence: str | None = None
    offset = 0

    def close(level: int) -> None:
        while open_sections and open_sections[-1][0] >= level:
            _, title, lines, owner = open_sections.pop()
            if owner:
                result[title] = "\n".join(lines).strip()

    for raw in body.splitlines(keepends=True):
        start, offset = offset, offset + len(raw)
        line = raw.rstrip("\r\n")
        opened = FENCE.match(line)
        heading = None
        if fence is None and opened:
            fence = opened.group("fence")
        elif fence is not None:
            if line.strip().startswith(fence[0] * len(fence)) and not line.strip().strip(fence[0]):
                fence = None
        elif not any(begin <= start < end for begin, end in comments):
            heading = HEADING.match(line)
        if heading:
            level = len(heading.group("level"))
            close(level)
            for _, _, lines, _ in open_sections:
                lines.append(line)
            title = normalize_title(heading.group("title"))
            owner = title not in result
            result.setdefault(title, "")  # reserva o lugar: a ordem é a do documento
            open_sections.append((level, title, [], owner))
            continue
        for _, _, lines, _ in open_sections:
            lines.append(line)
    close(0)
    return result


@functools.cache
def _equivalent_titles() -> dict[str, tuple[str, ...]]:
    """``{título normalizado: os equivalentes em outros idiomas}``, a partir de ``i18n.section_groups``."""
    table: dict[str, tuple[str, ...]] = {}
    for group in i18n.section_groups():
        names = sorted({normalize_title(name) for name in group})
        for name in names:
            table[name] = tuple(other for other in names if other != name)
    return table


def equivalent_titles(title: str) -> tuple[str, ...]:
    """Os equivalentes normalizados de ``title`` nos outros idiomas (vazio se não há)."""
    return _equivalent_titles().get(normalize_title(title), ())


def same_title(found: str, wanted: str) -> bool:
    """``found`` é o título ``wanted`` ou o equivalente dele em outro idioma."""
    found, wanted = normalize_title(found), normalize_title(wanted)
    return found == wanted or found in _equivalent_titles().get(wanted, ())


def find_section(found: dict[str, str], title: str) -> str | None:
    """O texto da seção ``title`` num resultado de ``sections``.

    Vale o título exato e, se ele não estiver lá, o mesmo título em outro idioma (``## Version`` num
    projeto em português, ``## Versão`` num em inglês): a troca de idioma não quebra issues e PRs
    abertos antes dela. Um título que não é equivalente de nenhum continua faltando.
    """
    wanted = normalize_title(title)
    if wanted in found:
        return found[wanted]
    return next((found[name] for name in _equivalent_titles().get(wanted, ()) if name in found), None)


def section(body: str, title: str) -> str | None:
    return find_section(sections(body), title)


def meaningful(text: str | None) -> str:
    """O texto sem comentários HTML e sem linhas que são só marcadores vazios do modelo."""
    cleaned = HTML_COMMENT.sub("", text or "").replace(NO_RESPONSE, "")
    return "\n".join(line for line in cleaned.splitlines() if not _PLACEHOLDER_LINE.match(line)).strip()


def marked_value(text: str | None, marker: str) -> str:
    """Valor de uma linha ``Marcador: valor`` (por exemplo o motivo de uma sobreposição)."""
    for line in meaningful(text).splitlines():
        head, _, tail = line.lstrip("-* ").partition(":")
        if same_title(head.strip().strip("*_"), marker) and tail.strip().strip("*_ "):
            return tail.strip().strip("*_ ")
    return ""


def checkboxes(text: str | None) -> list[tuple[bool, str]]:
    found = (CHECKBOX.match(line) for line in HTML_COMMENT.sub("", text or "").splitlines())
    return [(match.group("mark") != " ", match.group("label").strip()) for match in found if match]


def slugify(title: str, limit: int = 40) -> str:
    """``Corrigir a origem pública`` → ``corrigir-a-origem-publica``; corta em limite de palavra."""
    ascii_text = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")
    if len(slug) > limit:
        cut = slug[: limit + 1]
        slug = cut[: cut.rfind("-")] if "-" in cut[1:] else slug[:limit]
    return slug.rstrip("-") or i18n.t("text.slug.fallback")
