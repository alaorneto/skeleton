"""Leitura de mensagens de commit e de corpos Markdown de issues e PRs."""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass

_ISSUE = r"(?:(?P<repo>[\w.-]+/[\w.-]+))?#(?P<number>\d+)"
_CLOSING = r"close[sd]?|fix(?:e[sd])?|resolve[sd]?"
ISSUE_REFERENCE = re.compile(rf"\b(?P<keyword>{_CLOSING}|refs?|part of)\b\s*:?\s+{_ISSUE}", re.IGNORECASE)
CLOSING_KEYWORD = re.compile(rf"^(?:{_CLOSING})$", re.IGNORECASE)
ANY_ISSUE = re.compile(_ISSUE)
ITEM_ISSUE = re.compile(rf"^{_ISSUE}\b")
SQUASH_SUFFIX = re.compile(r"\(#(?P<number>\d+)\)\s*$")
MERGE_PR = re.compile(r"^Merge pull request #(?P<number>\d+) from ")
BRANCH_ISSUE = re.compile(r"(?:^|/)(\d+)-")
AUTOGENERATED = re.compile(r'^(?:Merge |Revert "|fixup! |squash! |amend! )')
REVERTS = re.compile(r"This reverts commit ([0-9a-f]{7,40})")
SCISSORS = re.compile(r"^# -+ >8 -+$", re.MULTILINE)
CONVENTIONAL = re.compile(r"^(?P<type>[a-z]+)(?:\((?P<scope>[^)]*)\))?(?P<bang>!)?: (?P<description>.+)$")
BREAKING_FOOTER = re.compile(r"^BREAKING[ -]CHANGE:\s*(?P<text>.+)$", re.MULTILINE)
HEADING = re.compile(r"^#{2,3}\s+(?P<title>.+?)\s*#*\s*$")
HTML_COMMENT = re.compile(r"<!--.*?-->", re.DOTALL)
CHECKBOX = re.compile(r"^\s*[-*]\s+\[(?P<mark>[ xX])\]\s+(?P<label>.*)$")
_PLACEHOLDER_LINE = re.compile(r"^[\s>*_`-]*(?:\[[ xX]?\])?[\s>*_`-]*$")
NO_RESPONSE = "_No response_"  # o que os formulários de issue do GitHub gravam em campos vazios


def same_repo(repo: str | None, repository: str | None) -> bool:
    return repo is None or repository is None or repo.lower() == repository.lower()


def clean_message(raw: str, comment_char: str = "#") -> str:
    """Remove o que o git descarta: tudo após a tesoura e as linhas de comentário."""
    match = SCISSORS.search(raw)
    if match:
        raw = raw[: match.start()]
    return "\n".join(line for line in raw.splitlines() if not line.startswith(comment_char)).strip()


def referenced_issues(text: str, repository: str | None = None, *, closing_only: bool = False) -> list[int]:
    """Números das issues citadas com palavra-chave; ignora outros repositórios.

    O sufixo ``(#N)`` do título de um squash conta como referência, mas nunca como fechamento.
    """
    numbers: list[int] = []
    for match in ISSUE_REFERENCE.finditer(text):
        if not same_repo(match.group("repo"), repository):
            continue
        if closing_only and not CLOSING_KEYWORD.match(match.group("keyword")):
            continue
        numbers.append(int(match.group("number")))
    if not closing_only:
        first_line = text.strip().splitlines()[0] if text.strip() else ""
        suffix = SQUASH_SUFFIX.search(first_line)
        if suffix:
            numbers.append(int(suffix.group("number")))
    return list(dict.fromkeys(numbers))


def is_autogenerated(message: str) -> bool:
    return bool(AUTOGENERATED.match(message))


def issue_from_branch(branch: str) -> int | None:
    match = BRANCH_ISSUE.search(branch)
    return int(match.group(1)) if match else None


@dataclass(frozen=True)
class Conventional:
    type: str
    scope: str | None
    breaking: bool
    description: str


def parse_conventional(subject: str) -> Conventional | None:
    match = CONVENTIONAL.match(subject.strip())
    if not match:
        return None
    return Conventional(match["type"], match["scope"], bool(match["bang"]), match["description"])


def breaking_notes(text: str) -> list[str]:
    """Textos dos rodapés ``BREAKING CHANGE:`` de uma mensagem de commit ou corpo de PR."""
    return [match.group("text").strip() for match in BREAKING_FOOTER.finditer(HTML_COMMENT.sub("", text))]


def normalize_title(title: str) -> str:
    return re.sub(r"\s+", " ", title).strip().strip(":").casefold()


def sections(body: str) -> dict[str, str]:
    """``{título normalizado: texto}`` para cada ``##`` ou ``###`` (os formulários do GitHub usam ``###``)."""
    result: dict[str, str] = {}
    current: str | None = None
    lines: list[str] = []
    in_fence = False
    for line in (body or "").splitlines():
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
        heading = None if in_fence else HEADING.match(line)
        if heading:
            if current is not None:
                result.setdefault(current, "\n".join(lines).strip())
            current, lines = normalize_title(heading.group("title")), []
        elif current is not None:
            lines.append(line)
    if current is not None:
        result.setdefault(current, "\n".join(lines).strip())
    return result


def section(body: str, title: str) -> str | None:
    return sections(body).get(normalize_title(title))


def meaningful(text: str | None) -> str:
    """O texto sem comentários HTML e sem linhas que são só marcadores vazios do modelo."""
    cleaned = HTML_COMMENT.sub("", text or "").replace(NO_RESPONSE, "")
    return "\n".join(line for line in cleaned.splitlines() if not _PLACEHOLDER_LINE.match(line)).strip()


def marked_value(text: str | None, marker: str) -> str:
    """Valor de uma linha ``Marcador: valor`` (por exemplo o motivo de uma sobreposição)."""
    wanted = marker.casefold()
    for line in meaningful(text).splitlines():
        head, _, tail = line.lstrip("-* ").partition(":")
        if head.strip().strip("*_").casefold() == wanted and tail.strip().strip("*_ "):
            return tail.strip().strip("*_ ")
    return ""


def checkboxes(text: str | None) -> list[tuple[bool, str]]:
    found = (CHECKBOX.match(line) for line in HTML_COMMENT.sub("", text or "").splitlines())
    return [(match.group("mark") != " ", match.group("label").strip()) for match in found if match]


def slugify(title: str, limit: int = 40) -> str:
    """``Corrigir a origem pública`` → ``corrigir-a-origem-publica``."""
    ascii_text = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")
    return slug[:limit].rstrip("-") or "trabalho"
