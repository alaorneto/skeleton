"""End-to-end use of the ledger by a consuming app (#550), through the public service API and the test kit.

The example notes app plays the consumer: its keys and rule come from ``ledger_consumer``. The
organization enables the ledger, applies the chart and binds the key; a member with no permission on
the book records a paid service (title and cash settlement) and posts and reverses a second one; a
monthly expense is generated by the job and paid; the period is locked; the trial balance closes and
the result matches; organization B sees nothing. Runtime role on PostgreSQL throughout.
"""

import datetime as dt

import pytest
from ledger_consumer import NOTE, RULE

from skeleton.contrib.ledger import recurrence
from skeleton.contrib.ledger.service_api import LedgerService
from skeleton.contrib.ledger.testing import account_id, enable_ledger, prepare_book
from skeleton.service_api import Conflict, NotFound
from skeleton.tenancy.context import system_context
from skeleton.testing.service_api import acting_as, build_service_scenario

pytestmark = pytest.mark.needs_example_app
APRIL = dt.date(2027, 4, 1)


def test_a_consuming_app_uses_the_ledger_end_to_end(skeleton_db):
    from examples.notes.models import Note

    scenario = build_service_scenario(Note, slug="ledger-scenario")
    service = LedgerService()
    for organization in (scenario.a, scenario.b):
        enable_ledger(organization)

    # The organization applies the chart and binds the consumer's key.
    with acting_as(scenario.admin_a, scenario.a) as admin:
        book = prepare_book(admin, bindings={"example_notes.service_revenue": "4.1"})
        cash, bank = account_id(admin, "1.1"), account_id(admin, "1.2")
    first = scenario.create(scenario.a, code="AT-1", title="Atendimento 1", visibility="organization")
    second = scenario.create(scenario.a, code="AT-2", title="Atendimento 2", visibility="organization")

    # A member with no permission on the book records a paid service: title and cash settlement.
    member = scenario.caller
    title = member(
        lambda actor: service.create_title(
            actor=actor,
            direction="receivable",
            amount=15000,
            due_date=APRIL,
            issue_date=APRIL,
            description="Atendimento AT-1",
            category_key="example_notes.service_revenue",
            idempotency_key="at-1",
            source_table=NOTE,
            source_id=first.pk,
            counterparty_name="Cliente Exemplo",
        )
    )()
    member(
        lambda actor: service.settle_title(
            actor=actor,
            title_id=title.sysid,
            amount=15000,
            date=APRIL,
            payment_account_id=cash,
            method="cash",
            expected_revision=title.revision,
            idempotency_key="at-1-pay",
        )
    )()

    # A second service is posted by the rule and reversed, both authorized by the source record.
    posted = member(
        lambda actor: service.post(
            actor=actor,
            rule=RULE,
            amounts={"total": 9000, "discount": 1000, "gross": 10000},
            date=dt.date(2027, 4, 2),
            description="Atendimento AT-2",
            source_id=second.pk,
            idempotency_key="at-2",
            accounts={"payment_account": cash},
        )
    )()
    member(
        lambda actor: service.reverse(
            actor=actor, entry_id=posted.sysid, date=dt.date(2027, 4, 3), reason="Lançado por engano"
        )
    )()
    assert [
        entry.kind
        for entry in member(
            lambda actor: service.entries_for_source(actor=actor, table_key=NOTE, record_id=second.pk)
        )()
    ] == [
        "rule",
        "reversal",
    ]

    # A monthly expense is generated by the job and paid from the bank.
    with acting_as(scenario.admin_a, scenario.a) as admin:
        rule = service.create_recurrence(
            actor=admin,
            direction="payable",
            amount=4000,
            description="Assinatura de software",
            category_key="ledger.expenses",
            frequency="monthly",
            start_date=dt.date(2027, 4, 10),
            days_ahead=5,
            idempotency_key="software",
        )
    with system_context(reason="test:ledger-scenario", organization_id=scenario.a.pk):
        assert recurrence.generate_due(today=dt.date(2027, 4, 5)) == 1
        assert recurrence.generate_due(today=dt.date(2027, 4, 5)) == 0
    with acting_as(scenario.admin_a, scenario.a) as admin:
        [expense] = service.titles(actor=admin, direction="payable").items
        assert expense.due_date == dt.date(2027, 4, 10) and service.recurrences(actor=admin)[0].sysid == rule.sysid
        service.settle_title(
            actor=admin,
            title_id=expense.sysid,
            amount=4000,
            date=dt.date(2027, 4, 10),
            payment_account_id=bank,
            method="transfer",
            expected_revision=expense.revision,
            idempotency_key="software-pay",
        )

        # The period is locked: nothing more is posted on or before it.
        locked = service.set_lock(actor=admin, locked_until=dt.date(2027, 4, 30), expected_revision=book.revision)
        assert locked.locked_until == dt.date(2027, 4, 30)

    with pytest.raises(Conflict) as error:
        member(
            lambda actor: service.post(
                actor=actor,
                rule=RULE,
                amounts={"total": 100, "discount": 0, "gross": 100},
                date=dt.date(2027, 4, 20),
                description="Atrasado",
                source_id=second.pk,
                idempotency_key="late",
                accounts={"payment_account": cash},
            )
        )()
    assert error.value.code == "period_locked"

    # The trial balance closes and the result matches the services and the expense.
    with acting_as(scenario.admin_a, scenario.a) as admin:
        trial = service.trial_balance(actor=admin, start=APRIL, end=dt.date(2027, 4, 30))
        assert trial.total_debit == trial.total_credit
        income = service.income_statement(actor=admin, start=APRIL, end=dt.date(2027, 4, 30))
        assert (income.revenue, income.expense, income.result) == (15000, 4000, 11000)
        assert service.balance(actor=admin, as_of=dt.date(2027, 4, 30), account_key="ledger.cash").balance == 15000
        assert service.balance(actor=admin, as_of=dt.date(2027, 4, 30), account_key="ledger.bank").balance == -4000

    # The member never reads the book itself.
    for read in (
        lambda actor: service.titles(actor=actor),
        lambda actor: service.trial_balance(actor=actor, start=APRIL, end=APRIL),
        lambda actor: service.entry(actor=actor, entry_id=posted.sysid),
    ):
        with pytest.raises(NotFound):
            member(read)()

    # Organization B sees nothing of A.
    with acting_as(scenario.admin_b, scenario.b) as admin_b:
        prepare_book(admin_b)
        assert service.titles(actor=admin_b).items == ()
        assert service.entries(actor=admin_b, start=APRIL, end=dt.date(2027, 4, 30)).items == ()
        assert service.recurrences(actor=admin_b) == ()
        with pytest.raises(NotFound):
            service.title(actor=admin_b, title_id=title.sysid)
        with pytest.raises(NotFound):
            service.entry(actor=admin_b, entry_id=posted.sysid)
    with pytest.raises(NotFound):
        member(
            lambda actor: service.entries_for_source(actor=actor, table_key=NOTE, record_id=first.pk),
            organization=scenario.b,
        )()
