"""Regras do vínculo commit/PR → issue (tools/workflow/github_issues.py)."""

from tools.workflow.github_issues import (
    clean_message,
    is_autogenerated,
    issue_from_branch,
    referenced_issues,
    validate_pr,
)

REPO = "alaorneto/skeleton"


def test_reference_keywords_and_trailers():
    assert referenced_issues("feat: x\n\nRefs #12") == [12]
    assert referenced_issues("fix: y\n\nRefs: #3\nCloses #4") == [3, 4]
    assert referenced_issues("docs: z\n\nPart of alaorneto/skeleton#7", REPO) == [7]
    assert referenced_issues("feat: squash subject (#21)") == [21]


def test_bare_hash_and_other_repositories_do_not_count():
    assert referenced_issues("feat: support #12 colors") == []
    assert referenced_issues("Refs other/repo#5", REPO) == []


def test_comments_and_scissors_are_ignored():
    raw = "feat: x\n# Refs #9\n# ------------------------ >8 ------------------------\nRefs #10\n"
    assert referenced_issues(clean_message(raw)) == []


def test_branch_number_and_autogenerated_messages():
    assert issue_from_branch("feat/42-platform-users") == 42
    assert issue_from_branch("42-hotfix") == 42
    assert issue_from_branch("ci/lint-and-pipeline") is None
    assert issue_from_branch("deps/bump-1-2") is None
    assert is_autogenerated("Merge branch 'main' into feat/1-x")
    assert is_autogenerated('Revert "feat: x"')
    assert not is_autogenerated("feat: merge forms")


def _issues(**by_number):
    return lambda number: by_number.get(f"n{number}")


def _labels(*names):
    return {"labels": [{"name": name} for name in names]}


def test_pr_requires_existing_typed_issue():
    fetch = _issues(n1=_labels("feature", "security"), n2=_labels(), n3={"pull_request": {}}, n4=_labels("epic"))
    assert validate_pr("Closes #1", REPO, fetch) == []
    assert validate_pr("Closes #1\nParte de #4\nRefs #4", REPO, fetch) == []
    assert validate_pr("Nada aqui", REPO, fetch)
    assert "label de tipo" in validate_pr("Closes #2", REPO, fetch)[0]
    assert "pull request" in validate_pr("Fixes #3", REPO, fetch)[0]
    assert "não existe" in validate_pr("Resolves #99", REPO, fetch)[0]
    assert "epics" in validate_pr("Refs #4", REPO, fetch)[0]


def test_pr_rejects_two_type_labels():
    fetch = _issues(n5=_labels("bug", "feature"))
    assert "exatamente um" in validate_pr("Closes #5", REPO, fetch)[0]
