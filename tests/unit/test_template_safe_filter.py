"""Templates never bypass autoescape with ``|safe`` or ``autoescape off`` outside an allowlist (#909).

Data-supplied values such as flow field ``help_text`` reach ``components/form-field.html`` as plain
strings. Django autoescape already renders ``SafeString`` values (like password validator help)
without ``|safe`` while escaping plain strings, so components must never apply ``|safe``.
"""

from __future__ import annotations

import re
from pathlib import Path

from django import forms
from django.contrib.auth.password_validation import password_validators_help_text_html
from django.template.loader import render_to_string
from django.utils import translation

ROOT = Path(__file__).resolve().parents[2]
SOURCES = [ROOT / "skeleton", ROOT / "examples"]

# Only validated organization brand CSS tokens (``#rrggbb`` generated by ``skeleton.tenancy.branding``)
# inside ``<style nonce="...">`` are allowed to bypass HTML escaping. Components have no allowlist.
SAFE_ALLOWED: dict[Path, set[str]] = {
    Path("skeleton/web/templates/skeleton/web/base.html"): {"organization_brand.css"},
    Path("skeleton/web/templates/skeleton/portal/base.html"): {"organization_brand.css"},
}

SAFE_FILTER = re.compile(r"\{\{[^}]*?(?P<expr>[A-Za-z0-9_.]+)\s*\|\s*safe\b[^}]*\}\}")
ANY_SAFE_FILTER = re.compile(r"\|\s*safe\b")
AUTOESCAPE_OFF = re.compile(r"\{%\s*autoescape\s+off\s*%\}")


def _templates():
    for source in SOURCES:
        yield from sorted(source.rglob("*.html"))


def _scan_text(relative: Path, text: str) -> list[str]:
    allowed_exprs = SAFE_ALLOWED.get(relative, set())
    offenders: list[str] = []
    for line_no, line in enumerate(text.splitlines(), start=1):
        if AUTOESCAPE_OFF.search(line):
            offenders.append(f"{relative}:{line_no}: autoescape off")
        if ANY_SAFE_FILTER.search(line):
            matches = list(SAFE_FILTER.finditer(line))
            if not matches:
                offenders.append(f"{relative}:{line_no}: |safe")
                continue
            for match in matches:
                expr = match.group("expr")
                if expr not in allowed_exprs:
                    offenders.append(f"{relative}:{line_no}: {expr}|safe")
    return offenders


def test_templates_never_use_safe_outside_allowlist():
    offenders: list[str] = []
    for path in _templates():
        relative = path.relative_to(ROOT)
        offenders.extend(_scan_text(relative, path.read_text(encoding="utf-8")))
    assert offenders == [], "unexpected |safe or autoescape off in templates: " + ", ".join(offenders)


def test_components_have_no_safe_allowlist():
    for path in SAFE_ALLOWED:
        assert "components" not in path.parts


def test_the_scan_catches_safe_in_components_and_autoescape_off():
    component = Path("skeleton/web/templates/skeleton/web/components/form-field.html")
    assert _scan_text(component, "{{ field.help_text|safe }}") == [f"{component}:1: field.help_text|safe"]
    assert _scan_text(component, "{{ value | safe }}") == [f"{component}:1: value|safe"]
    assert _scan_text(component, "{% autoescape off %}{{ x }}{% endautoescape %}") == [f"{component}:1: autoescape off"]
    assert _scan_text(component, "{{ field.help_text }}") == []


def test_form_field_escapes_plain_help_text_and_keeps_password_help_safe_string():
    class SampleForm(forms.Form):
        note = forms.CharField(
            label="Nota",
            required=False,
            help_text="<a href='https://evil.test'>Clique para validar</a>",
        )
        new_password = forms.CharField(
            label="Nova senha",
            required=True,
            widget=forms.PasswordInput,
            help_text=password_validators_help_text_html(),
        )

    form = SampleForm()
    with translation.override("pt-br"):
        html = render_to_string("skeleton/web/components/form-fields.html", {"form": form})
    assert "<a href=" not in html
    assert "&lt;a href=&#x27;https://evil.test&#x27;&gt;Clique para validar&lt;/a&gt;" in html
    assert "<ul>" in html and "<li>" in html
