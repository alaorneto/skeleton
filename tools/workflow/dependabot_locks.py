"""Locks dos PRs do Dependabot regenerados pelo comando oficial do uv (docs/testing.md).

O Dependabot regenera ``requirements*.txt`` no estilo pip-compile (sem ``pip`` e
``setuptools``, com extras nos nomes) ou muda só os ``.in``. O workflow
``dependabot-locks`` usa este script, só com a biblioteca padrão:

- ``regenerate --base SHA``: troca os locks do checkout pelos da base ``SHA`` e roda
  os comandos ``uv pip compile`` do README com ``--upgrade-package`` restrito ao que
  o PR mudou: a versão de cada pacote que mudou nos locks e o nome de cada linha nova
  dos ``.in``. Com ``-o``, o uv usa o lock da base como preferência e não atualiza
  pacotes de carona. ``--no-build`` impede que o compile execute código de build de
  sdists, e ``--custom-compile-command`` mantém o cabeçalho do comando oficial.
- ``check-artifact DIR``: valida os locks produzidos pelo job sem permissão de
  escrita antes de o job com token commitá-los. Aceita só os dois arquivos, com o
  cabeçalho oficial e toda requisição fixada com ``==`` e hash; recusa opções de
  índice, URLs diretas, editáveis e qualquer outra linha.
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

LOCKS: tuple[tuple[str, str], ...] = (
    ("requirements.in", "requirements.txt"),
    ("requirements-dev.in", "requirements-dev.txt"),
)
COMPILE_OPTIONS = (
    "--python-version",
    "3.14",
    "--python-platform",
    "x86_64-manylinux_2_28",
    "--generate-hashes",
)
HEADER_FIRST_LINE = "# This file was autogenerated by uv via the following command:"
MAX_LOCK_BYTES = 4 * 1024 * 1024

_NAME = r"[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?"
_LOCK_PIN = re.compile(rf"^(?P<name>{_NAME})(?:\[[^\]]*\])?==(?P<version>[^\s;\\]+)")
_IN_NAME = re.compile(rf"^(?P<name>{_NAME})")
_LOCK_REQUIREMENT = re.compile(rf"^{_NAME}==[A-Za-z0-9][A-Za-z0-9.+!_-]*(?:\s+--hash=sha256:[0-9a-f]{{64}})+$")


def official_command(source: str, output: str) -> str:
    """Comando de "Atualizar locks" do README, gravado no cabeçalho do lock."""
    return " ".join(("uv pip compile", *COMPILE_OPTIONS, source, "-o", output))


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_versions(text: str) -> dict[str, str]:
    """Versão fixada de cada pacote de um lock (extras no nome são ignorados)."""
    versions: dict[str, str] = {}
    for line in text.splitlines():
        match = _LOCK_PIN.match(line)
        if match:
            versions[normalize(match["name"])] = match["version"]
    return versions


def in_requirements(text: str) -> dict[str, str]:
    """Linha normalizada de cada requisição de um ``.in``, por nome de pacote."""
    requirements: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        match = _IN_NAME.match(line)
        if match:
            requirements[normalize(match["name"])] = re.sub(r"\s+", "", line).lower()
    return requirements


def upgrade_specs(
    base_locks: Iterable[str],
    head_locks: Iterable[str],
    base_ins: Iterable[str],
    head_ins: Iterable[str],
) -> list[str]:
    """Argumentos de ``--upgrade-package`` para tudo o que o PR mudou, lock a lock.

    Pacote com versão nova (ou novo) nos locks do PR entra fixado nessa versão.
    Pacote cuja linha mudou num ``.in`` sem versão nova no lock entra só pelo nome,
    e o uv escolhe a versão dentro do novo limite. Pacotes que o PR removeu do lock
    (``pip`` e ``setuptools`` no estilo pip-compile) não entram.
    """
    pinned: dict[str, str] = {}
    for base_lock, head_lock in zip(base_locks, head_locks, strict=True):
        base_versions = lock_versions(base_lock)
        for name, version in lock_versions(head_lock).items():
            if base_versions.get(name) != version:
                pinned.setdefault(name, version)  # o lock runtime vem primeiro e prevalece
    base_lines = _merge(in_requirements(text) for text in base_ins)
    head_lines = _merge(in_requirements(text) for text in head_ins)
    changed_in = {name for name, line in head_lines.items() if base_lines.get(name) != line}
    specs = [f"{name}=={version}" for name, version in sorted(pinned.items())]
    specs += sorted(changed_in - pinned.keys())
    return specs


def _merge(mappings: Iterable[Mapping[str, str]]) -> dict[str, str]:
    merged: dict[str, str] = {}
    for mapping in mappings:
        merged.update(mapping)
    return merged


def _git_show(root: Path, revision: str, path: str) -> str:
    result = subprocess.run(
        ["git", "show", f"{revision}:{path}"],
        cwd=root,
        capture_output=True,
        check=False,
        encoding="utf-8",
    )
    return result.stdout if result.returncode == 0 else ""


def regenerate(base: str, root: Path = Path(".")) -> int:
    if not re.fullmatch(r"[0-9a-f]{7,64}", base):
        print("regenerate: --base precisa ser um SHA de commit.", file=sys.stderr)
        return 2
    head_ins = [(root / source).read_text(encoding="utf-8") for source, _ in LOCKS]
    head_locks = [_read(root / output) for _, output in LOCKS]
    base_ins = [_git_show(root, base, source) for source, _ in LOCKS]
    base_locks = [_git_show(root, base, output) for _, output in LOCKS]
    specs = upgrade_specs(base_locks, head_locks, base_ins, head_ins)
    print("Pacotes atualizados pelo PR:", ", ".join(specs) or "nenhum")
    for (source, output), base_lock in zip(LOCKS, base_locks, strict=True):
        (root / output).write_text(base_lock, encoding="utf-8", newline="\n")
        command = [
            "uv",
            "pip",
            "compile",
            *COMPILE_OPTIONS,
            "--no-build",
            "--custom-compile-command",
            official_command(source, output),
            "--quiet",
            source,
            "-o",
            output,
        ]
        for spec in specs:
            command += ["--upgrade-package", spec]
        subprocess.run(command, cwd=root, check=True)
    return 0


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def lock_problems(name: str, text: str) -> list[str]:
    """Motivos para recusar um lock; lista vazia quando ele pode ser commitado."""
    source = next((source for source, output in LOCKS if output == name), None)
    if source is None:
        return [f"{name}: arquivo inesperado"]
    lines = text.split("\n")
    expected = [HEADER_FIRST_LINE, f"#    {official_command(source, name)}"]
    if lines[:2] != expected:
        return [f"{name}: cabeçalho diferente do comando oficial do README"]
    if "\r" in text or not text.endswith("\n"):
        return [f"{name}: fim de linha diferente de LF"]
    problems: list[str] = []
    seen: set[str] = set()
    for number, logical in _logical_lines(lines[2:], first=3):
        stripped = logical.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if not _LOCK_REQUIREMENT.match(stripped):
            problems.append(f"{name}:{number}: linha fora do formato 'pacote==versão --hash=sha256:...'")
            continue
        package = normalize(stripped.split("==", 1)[0])
        if package in seen:
            problems.append(f"{name}:{number}: {package} repetido")
        seen.add(package)
    if not seen:
        problems.append(f"{name}: nenhuma requisição")
    return problems


def _logical_lines(lines: Sequence[str], *, first: int) -> Iterable[tuple[int, str]]:
    buffer: list[str] = []
    start = first
    for offset, line in enumerate(lines):
        if not buffer:
            start = first + offset
        if line.endswith("\\"):
            buffer.append(line[:-1])
            continue
        buffer.append(line)
        yield start, " ".join(part.strip() for part in buffer)
        buffer = []
    if buffer:
        yield start, " ".join(part.strip() for part in buffer) + " \\"


def check_artifact(directory: Path) -> int:
    expected = {output for _, output in LOCKS}
    problems: list[str] = []
    entries = sorted(directory.iterdir()) if directory.is_dir() else []
    names = {entry.name for entry in entries}
    if names != expected:
        problems.append(f"o artifact precisa ter exatamente {sorted(expected)}; tem {sorted(names)}")
    for entry in entries:
        if entry.name not in expected:
            continue
        if entry.is_symlink() or not entry.is_file():
            problems.append(f"{entry.name}: não é um arquivo regular")
            continue
        if entry.stat().st_size > MAX_LOCK_BYTES:
            problems.append(f"{entry.name}: maior que {MAX_LOCK_BYTES} bytes")
            continue
        try:
            text = entry.read_bytes().decode("utf-8")
        except UnicodeDecodeError:
            problems.append(f"{entry.name}: não é UTF-8")
            continue
        problems += lock_problems(entry.name, text)
    for problem in problems:
        print(f"::error::{problem}")
    if not problems:
        print("Locks do artifact válidos:", ", ".join(sorted(names)))
    return 1 if problems else 0


def main(argv: Sequence[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):  # console do Windows em cp1252
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) == 3 and args[:2] == ["regenerate", "--base"]:
        return regenerate(args[2])
    if len(args) == 2 and args[0] == "check-artifact":
        return check_artifact(Path(args[1]))
    print("uso: dependabot_locks.py regenerate --base SHA | check-artifact DIR", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
