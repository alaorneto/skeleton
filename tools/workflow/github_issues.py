"""Vínculo entre trabalho versionado e issues do GitHub (docs/workflow.md).

Subcomandos, todos só com a biblioteca padrão:

- ``commit-msg ARQUIVO``: hook ``commit-msg`` do pre-commit. Aceita mensagens que
  referenciam uma issue; senão acrescenta ``Refs: #N`` a partir da branch
  ``<tipo>/<N>-<slug>``; senão recusa o commit.
- ``check-pr``: usado pelo CI. Lê ``PR_BODY`` e ``GITHUB_REPOSITORY`` e exige que
  o PR referencie ao menos uma issue existente com exatamente um label de tipo.
- ``sync-labels``: cria/atualiza os labels de classificação com ``gh``.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from collections.abc import Callable, Sequence
from pathlib import Path

TYPE_LABELS: dict[str, tuple[str, str]] = {
    "bug": ("d73a4a", "Comportamento incorreto, regressão ou falha de segurança existente"),
    "feature": ("1d76db", "Nova funcionalidade"),
    "enhancement": ("a2eeef", "Melhoria de funcionalidade existente"),
    "documentation": ("0075ca", "Somente documentação"),
    "refactor": ("fbca04", "Reestruturação sem mudança de comportamento"),
    "test": ("bfd4f2", "Somente testes, fixtures ou evidência de verificação"),
    "ci": ("5319e7", "Pipeline e checks automáticos"),
    "chore": ("c5def5", "Dependências, ferramentas e configuração de desenvolvimento"),
}
EXTRA_LABELS: dict[str, tuple[str, str]] = {
    "security": ("b60205", "Impacto em isolamento, autorização, autenticação, auditoria ou segredos"),
    "epic": ("3e4b9e", "Acompanhamento de um plano com várias issues"),
}

_ISSUE = r"(?:(?P<repo>[\w.-]+/[\w.-]+))?#(?P<number>\d+)"
ISSUE_REFERENCE = re.compile(
    rf"\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?|refs?|part of)\b\s*:?\s+{_ISSUE}",
    re.IGNORECASE,
)
SQUASH_SUFFIX = re.compile(r"\(#(?P<number>\d+)\)\s*$")
BRANCH_ISSUE = re.compile(r"(?:^|/)(\d+)-")
AUTOGENERATED = re.compile(r'^(?:Merge |Revert "|fixup! |squash! |amend! )')
SCISSORS = re.compile(r"^# -+ >8 -+$", re.MULTILINE)


def clean_message(raw: str, comment_char: str = "#") -> str:
    """Remove o que o git descarta: tudo após a tesoura e linhas de comentário."""
    match = SCISSORS.search(raw)
    if match:
        raw = raw[: match.start()]
    return "\n".join(line for line in raw.splitlines() if not line.startswith(comment_char)).strip()


def referenced_issues(text: str, repository: str | None = None) -> list[int]:
    """Números das issues citadas com palavra-chave; ignora outros repositórios."""
    numbers: list[int] = []
    for match in ISSUE_REFERENCE.finditer(text):
        repo = match.group("repo")
        if repo and repository and repo.lower() != repository.lower():
            continue
        numbers.append(int(match.group("number")))
    first_line = text.strip().splitlines()[0] if text.strip() else ""
    suffix = SQUASH_SUFFIX.search(first_line)
    if suffix:
        numbers.append(int(suffix.group("number")))
    return list(dict.fromkeys(numbers))


def is_autogenerated(message: str) -> bool:
    return bool(AUTOGENERATED.match(message))


def issue_from_branch(branch: str) -> int | None:
    match = BRANCH_ISSUE.search(branch)
    return int(match.group(1)) if match else None


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout.strip()


def commit_msg(path: Path) -> int:
    message = clean_message(path.read_text(encoding="utf-8", errors="replace"))
    if not message or is_autogenerated(message) or referenced_issues(message):
        return 0
    try:
        branch = _git("symbolic-ref", "--short", "HEAD")  # funciona antes do 1º commit; falha se HEAD destacado
    except (OSError, subprocess.CalledProcessError):
        branch = ""
    issue = issue_from_branch(branch)
    if issue is not None:
        _git(
            "interpret-trailers",
            "--in-place",
            "--if-exists",
            "addIfDifferent",
            "--trailer",
            f"Refs: #{issue}",
            str(path),
        )
        print(f"commit-msg: 'Refs: #{issue}' acrescentado a partir da branch {branch}.")
        return 0
    print(
        "commit-msg: o commit precisa referenciar uma issue do GitHub.\n"
        "  Acrescente um trailer 'Refs #N' (ou trabalhe numa branch <tipo>/<N>-<slug>).\n"
        "  Sem issue? Crie uma antes: veja docs/workflow.md e o skill issue-workflow.",
        file=sys.stderr,
    )
    return 1


IssueFetcher = Callable[[int], dict[str, object] | None]


def validate_pr(body: str, repository: str, fetch: IssueFetcher) -> list[str]:
    """Erros que impedem o PR; lista vazia quando o vínculo está correto."""
    numbers = referenced_issues(body, repository)
    if not numbers:
        return ["O corpo do PR não referencia issue: use `Closes #N` (entrega completa) ou `Refs #N` (parcial)."]
    errors: list[str] = []
    typed = 0
    for number in numbers:
        issue = fetch(number)
        if issue is None:
            errors.append(f"#{number} não existe em {repository}.")
            continue
        if "pull_request" in issue:
            errors.append(f"#{number} é um pull request, não uma issue.")
            continue
        raw_labels = issue.get("labels")
        labels = (
            {str(label.get("name")) for label in raw_labels if isinstance(label, dict)}
            if isinstance(raw_labels, list)
            else set()
        )
        if "epic" in labels:
            continue
        types = sorted(labels & TYPE_LABELS.keys())
        if len(types) != 1:
            found = ", ".join(types) or "nenhum"
            errors.append(
                f"#{number} precisa de exatamente um label de tipo ({', '.join(TYPE_LABELS)}); encontrado: {found}."
            )
            continue
        typed += 1
    if typed == 0 and not errors:
        errors.append("O PR referencia apenas epics; cite a issue filha entregue (`Closes #N`).")
    return errors


def _gh_fetch(repository: str) -> IssueFetcher:
    def fetch(number: int) -> dict[str, object] | None:
        result = subprocess.run(
            ["gh", "api", f"repos/{repository}/issues/{number}"], capture_output=True, text=True, check=False
        )
        if result.returncode != 0:
            return None
        data = json.loads(result.stdout)
        return data if isinstance(data, dict) else None

    return fetch


def check_pr() -> int:
    repository = os.environ["GITHUB_REPOSITORY"]
    errors = validate_pr(os.environ.get("PR_BODY", ""), repository, _gh_fetch(repository))
    for error in errors:
        print(f"::error title=Vínculo com issue::{error}")
    if not errors:
        print("PR vinculado a issue classificada.")
    return 1 if errors else 0


def sync_labels() -> int:
    for name, (color, description) in {**TYPE_LABELS, **EXTRA_LABELS}.items():
        subprocess.run(
            ["gh", "label", "create", name, "--color", color, "--description", description, "--force"], check=True
        )
        print(f"label {name} ok")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):  # hooks do git no Windows recebem pipe em cp1252
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    args = list(sys.argv[1:] if argv is None else argv)
    if args[:1] == ["commit-msg"] and len(args) == 2:
        return commit_msg(Path(args[1]))
    if args == ["check-pr"]:
        return check_pr()
    if args == ["sync-labels"]:
        return sync_labels()
    print("uso: github_issues.py commit-msg ARQUIVO | check-pr | sync-labels", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
