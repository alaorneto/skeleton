#!/bin/sh
# Entrypoint of the PostgreSQL of one instance on the data server (#679). Runs as root before the
# image's own entrypoint: writes pg_hba.conf for the network of the application nodes only, copies
# the TLS files to where PostgreSQL accepts them (owned by postgres, key 0600), then hands over.
# pgbouncer_hba.conf is the same rule for the clients of the optional pooler (#676), which reaches
# PostgreSQL by the socket of a volume only it shares: the one "local" entry of the runtime role.
set -eu

: "${DATA_CLIENT_CIDR:?Define the network of the application nodes}"
target=/var/lib/postgresql/skeleton
mkdir -p "$target"
cat > "$target/pg_hba.conf" <<EOF
# Generated by deploy/data-server/postgres-entrypoint.sh: edit DATA_CLIENT_CIDR, not this file.
# The administrator only through the container's own socket; the instance's roles only over TLS
# from the application nodes, with SCRAM passwords.
local   all   postgres                                                  trust
local   all   skeleton_runtime                                          scram-sha-256
hostssl all   skeleton_owner,skeleton_runtime,skeleton_agent  ${DATA_CLIENT_CIDR}  scram-sha-256
EOF
cat > "$target/pgbouncer_hba.conf" <<EOF
# Generated by deploy/data-server/postgres-entrypoint.sh: the pooler's clients, like PostgreSQL's.
hostssl all   skeleton_runtime  ${DATA_CLIENT_CIDR}  scram-sha-256
EOF
cp /opt/data-server/tls/server.crt "$target/server.crt"
cp /opt/data-server/tls/server.key "$target/server.key"
chown -R postgres:postgres "$target"
chmod 0755 "$target"  # The pooler reads pgbouncer_hba.conf; the rest stays the server's own.
chmod 0600 "$target/server.key" "$target/pg_hba.conf"
chmod 0644 "$target/pgbouncer_hba.conf"
# The pooler's user list: SCRAM needs the password itself, readable only by the pooler's user
# (uid 70 in its image), never by the other users of this volume.
printf '"skeleton_runtime" "%s"\n' "$SKELETON_RUNTIME_DB_PASSWORD" > "$target/pgbouncer_userlist.txt"
chown 70:70 "$target/pgbouncer_userlist.txt"
chmod 0600 "$target/pgbouncer_userlist.txt"
exec docker-entrypoint.sh "$@"
